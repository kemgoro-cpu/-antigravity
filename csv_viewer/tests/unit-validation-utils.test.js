'use strict';
const assert = require('node:assert/strict');
const U = require('../unit-validation-utils');
const seconds = { timeScaleSource: 'unit', timeScaleUnit: 's', timeScale: 1 };
const valid = { actualUnit: 'km/h', targetUnit: 'km/h', fuelUnit: 'L/h', hasFuel: true, useModeTrace: false, timeMetadata: seconds };
assert.equal(U.validateDriveInputs(valid).ok, true);
assert.equal(U.validateDriveInputs(valid).fuelAllowed, true);
assert.equal(U.validateDriveInputs({ ...valid, actualUnit: 'm/s' }).ok, false);
assert.equal(U.validateDriveInputs({ ...valid, actualUnit: '' }).issues.find(x => x.field === 'actual').status, 'unknown');
assert.equal(U.validateDriveInputs({ ...valid, targetUnit: 'mph' }).ok, false);
assert.equal(U.validateDriveInputs({ ...valid, targetUnit: undefined, useModeTrace: true }).ok, true);
const badFuel = U.validateDriveInputs({ ...valid, fuelUnit: 'g/s' });
assert.equal(badFuel.ok, true, 'Invalid fuel must not suppress valid speed metrics');
assert.equal(badFuel.fuelAllowed, false, 'Mass flow must not be interpreted as L/h');
assert.equal(U.validateDriveInputs({ ...valid, fuelUnit: '' }).fuelAllowed, false);
assert.equal(U.validateDriveInputs({ ...valid, hasFuel: false }).issues.length, 0);
assert.equal(U.checkUnit('speed', ' [ km / h ] ').ok, true);
assert.equal(U.checkUnit('fuel', 'Ｌ／ｈ').ok, true);
assert.equal(U.checkUnit('fuel', 'mL/h').ok, false);
assert.equal(U.checkUnit('fuel', 'L/min').ok, false);
assert.equal(U.checkTime({ timeScaleSource: 'unit', timeScaleUnit: 'ms', timeScale: 0.001 }).ok, true);
assert.equal(U.checkTime({ timeScaleSource: 'header', timeScaleUnit: 's', timeScale: 1 }).ok, true);
assert.equal(U.checkTime({ timeScaleSource: 'manual', timeScaleUnit: 's', timeScale: 1 }).ok, true);
assert.equal(U.checkTime({ timeScaleSource: 'auto', timeScaleUnit: 's', timeScale: 1 }).ok, false, 'Guessed seconds require user confirmation');
assert.equal(U.checkTime({ timeScaleSource: 'unit', timeScaleUnit: 'ms', timeScale: 1 }).ok, false, 'Unnormalized milliseconds must not be treated as seconds');
assert.equal(U.checkTime({ timeScaleSource: 'unit', timeScaleUnit: 'min', timeScale: 1 }).ok, false);
assert.equal(U.checkTime({}).ok, false);
const data = { resultSignature: 'old', results: [{ result: { total: { rmsse: 0 } } }] };
assert.equal(U.resultState(data, 'old').status, 'current');
assert.equal(U.resultState(data, 'new').status, 'stale');
assert.equal(U.resultState({ ...data, draftDirty: true }, 'old').status, 'stale');
assert.equal(U.resultState({ ...data, calculating: true }, 'old').status, 'stale');
assert.equal(U.resultState({ ...data, results: [{ result: null }] }, 'old').status, 'empty');
assert.equal(U.resultState({ ...data, resultSignature: undefined }, 'old').status, 'empty');
assert.equal(U.resultState({ ...data, resultSignature: 'new', draftDirty: false }, 'new').status, 'current');
assert.deepEqual(data.results[0].result.total, { rmsse: 0 }, 'Validation must not change numeric results');
console.log('unit-validation-utils: correct, missing and mismatched units; time normalization; stale-result contracts passed');
