'use strict';
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const upgrade = require('./upgrade-review.cjs');
const progress = require('./implementation-status.json');
const proposals = require('./recommendations.cjs');
const statusOf = item => progress.items.find(p=>p.originalRank===item.originalRank)?.status || progress.defaultStatus;
const statusCounts = proposals.reduce((counts,item)=>(counts[statusOf(item)]++,counts),{complete:0,partial:0,pending:0});
const remaining = statusCounts.partial + statusCounts.pending;
const idsFor = status => proposals.filter(item=>statusOf(item)===status).map(item=>'idea-'+item.rank);
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const records=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[],network=[];
  page.on('pageerror',err=>errors.push(err.message));
  page.on('request',req=>{if(/^https?:/.test(req.url()))network.push(req.url());});
  await page.goto(pathToFileURL(path.join(__dirname,'report.html')).href);
  assert.equal(await page.locator('.candidate').count(),55);
  assert.equal(await page.locator('table.products tbody tr').count(),37);
  assert.equal(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).length),0);
  assert.deepEqual(await page.locator('a[href^="#"]').evaluateAll(as=>as.filter(a=>!document.getElementById(a.hash.slice(1))).map(a=>a.hash)),[]);
  assert.equal(await page.locator('.candidate:visible').count(),remaining);
  assert.equal(await page.locator('.candidate-check:checked').count(),statusCounts.complete);
  assert.equal(await page.locator('.candidate-check').evaluateAll(boxes=>boxes.filter(box=>box.indeterminate).length),statusCounts.partial);
  assert.equal(await page.locator('[data-consolidation] input:checked').count(),upgrade.consolidation.items.filter(item=>item.status==='complete').length);
  const exported=JSON.parse(fs.readFileSync(path.join(__dirname,'recommendations.json'),'utf8'));
  const manifest=JSON.parse(fs.readFileSync(path.join(__dirname,'research-manifest.json'),'utf8'));
  assert.equal(exported.filter(item=>item.upgrade).length,55);
  assert.deepEqual(manifest.upgradeAudit.counts,upgrade.counts);
  assert.equal(await page.locator('.upgrade-detail').count(),55);
  assert.equal(await page.locator('.upgrade-bundle').count(),6);
  for(const [mode,count] of Object.entries(upgrade.counts)){
   await page.locator(`[data-upgrade-view="${mode}"]`).click();
   assert.equal(await page.locator('.candidate:visible').count(),count);
   assert.equal(await page.locator('#status').inputValue(),'');
   assert.equal(await page.locator('.candidate:visible').evaluateAll((cards,mode)=>cards.every(card=>card.dataset.upgrade===mode),mode),true);
  }
  await page.locator('[data-upgrade-view="in-place"]').click();
  assert.equal(await page.locator('.candidate:visible').count(),upgrade.inPlaceCount);
  await page.locator('#status').selectOption('complete');
  assert.equal(await page.locator('.candidate:visible').count(),statusCounts.complete);
  await page.locator('#upgrade').selectOption('defer');
  assert.equal(await page.locator('.candidate:visible').count(),0);
  assert.equal(await page.locator('#empty-result').isVisible(),true);
  await page.locator('#reset').click();
  await page.locator('#q').fill('静的ショートカット一覧');
  assert.deepEqual(await page.locator('.candidate:visible').evaluateAll(cards=>cards.map(card=>card.id)),['idea-29']);
  await page.locator('[data-status-view="complete"]').click();
  assert.deepEqual(await page.locator('.candidate:visible').evaluateAll(cards=>cards.map(card=>card.id)),idsFor('complete'));
  await page.locator('#status').selectOption('partial');
  assert.deepEqual(await page.locator('.candidate:visible').evaluateAll(cards=>cards.map(card=>card.id)),idsFor('partial'));
  assert.match(await page.locator('#idea-3 .implementation-detail').textContent(),/自動スクロール/);
  assert.match(await page.locator('#idea-6 .remaining-task').first().innerText(),/換算候補/);
  await page.locator('#q').fill('m/s');
  assert.equal(await page.locator('.candidate:visible').count(),1);
  await page.locator('#q').fill('存在しない提案xyz');
  assert.equal(await page.locator('.candidate:visible').count(),0);
  assert.equal(await page.locator('#empty-result').isVisible(),true);
  await page.locator('#reset').click();
  await page.locator('#status').selectOption('pending');
  assert.equal(await page.locator('.candidate:visible').count(),statusCounts.pending);
  await page.locator('#reset').click();
  await page.locator('#phase').selectOption('A');
  assert.equal(await page.locator('.candidate:visible').count(),10);
  await page.locator('#cost').selectOption('S');
  assert.equal(await page.locator('.candidate:visible').count(),1);
  await page.locator('#reset').click();
  assert.equal(await page.locator('.candidate:visible').count(),55);
  await page.locator('#q').fill('XY');
  assert.ok(await page.locator('.candidate:visible').count()>0);
  assert.ok(await page.locator('.candidate:visible').count()<55);
  await page.locator('#reset').click();
  await page.locator('#expand').click();
  assert.equal(await page.locator('.candidate details[open]').count(),110);
  await page.locator('#status').selectOption('remaining');
  for(const width of [1440,900,390]){
   await page.setViewportSize({width,height:1080});
   await page.evaluate(()=>window.scrollTo(0,0));
   const sizes=await page.evaluate(()=>({viewport:window.innerWidth,body:document.body.scrollWidth,root:document.documentElement.scrollWidth}));
   assert.ok(sizes.root<=width+1,JSON.stringify(sizes));
   records.push(sizes);
   await page.screenshot({path:path.join(__dirname,`screenshots/report-${width}.png`)});
  }
  await page.setViewportSize({width:1440,height:1080});
  await page.locator('#upgrade-review').evaluate(el=>el.scrollIntoView({block:'start'}));
  await page.screenshot({path:path.join(__dirname,'screenshots/report-upgrade.png')});
  await page.locator('.upgrade-subheading').evaluate(el=>el.scrollIntoView({block:'start'}));
  await page.screenshot({path:path.join(__dirname,'screenshots/report-upgrade-plan.png')});
  await page.locator('#ranking').evaluate(el=>el.scrollIntoView({block:'start'}));
  await page.screenshot({path:path.join(__dirname,'screenshots/report-ranking.png')});
  assert.deepEqual(errors,[]);
  assert.deepEqual(network,[]);
  await page.goto(pathToFileURL(path.join(__dirname,'report.html')).href+'#idea-1');
  assert.equal(await page.locator('#idea-1').isVisible(),true,'direct links reveal a completed card');
  await page.locator('#upgrade').selectOption('defer');
  await page.evaluate(()=>location.hash='idea-2');
  await page.waitForFunction(()=>!document.getElementById('idea-2').hidden);
  assert.equal(await page.locator('#upgrade').inputValue(),'');
  const result={products:37,proposals:55,implementationStatus:{...statusCounts,remaining},consolidation:upgrade.consolidation.items.map(item=>({order:item.order,status:item.status})),upgradeAudit:{counts:upgrade.counts,inPlaceCount:upgrade.inPlaceCount,coverage:55,filters:'passed'},defaultView:'remaining',filters:'passed',images:'loaded',internalLinks:'valid',widths:records,pageErrors:errors,externalRequests:network};
  fs.writeFileSync(path.join(__dirname,'report-validation.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(err=>{console.error(err);process.exitCode=1;});
